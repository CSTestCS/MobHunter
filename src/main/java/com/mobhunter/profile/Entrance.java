package com.mobhunter.profile;

/** How a Monstrous creature arrives when the final clue is disturbed. */
public enum Entrance {
    /** Claws its way up out of the earth, like a warden. */
    BURROW,
    /** Plummets from the sky and crashes down. */
    SKY_DIVE,
    /** Leaps in from far away and lands with a shockwave. */
    CRASH_LANDING,
    /** Bursts out of a geyser of water. */
    GEYSER,
    /** Tears open a rift in reality and steps through. */
    RIFT,
    /** Arrives in a pillar of lightning. */
    THUNDERSTRIKE,
    /** Erupts from a column of fire and smoke. */
    INFERNO,
    /** Coalesces from bones / slime / scrap gathered from the surroundings. */
    ASSEMBLE,
    /** Unfolds out of a swirling fog. */
    FOG
}
